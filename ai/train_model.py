"""Train a SYNTHETIC demonstration Random Forest, not a physically validated fault model.

The dataset is generated by distinct runs. No overlapping windows cross split boundaries.
Use actual labelled motor run manifests and real feature windows for scientific evaluation.
"""
import argparse
import json
import sys
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from edge_ai_twin.features import FEATURE_NAMES, extract_features
from edge_ai_twin.simulation import SCENARIOS, generate_batch


def build_demo_dataset(runs_per_class=12, windows_per_run=8):
    rows = []
    for class_idx, scenario in enumerate(SCENARIOS):
        for run in range(runs_per_class):
            run_id = f"synthetic_{scenario}_{run:02d}"
            for window in range(windows_per_run):
                batch = generate_batch(
                    scenario, sequence=window + 1, run_id=run_id,
                    seed=10000 * class_idx + 101 * run + window,
                )
                sensor = {topic.split("/")[-1]: payload for topic, payload in batch.items()}
                rows.append({
                    **extract_features(sensor),
                    "label": scenario.upper(),
                    "run_id": run_id,
                    "run_number": run,
                })
    return pd.DataFrame(rows)


def train(out_dir, runs_per_class=12):
    if runs_per_class < 6:
        raise ValueError("Need >=6 independent synthetic runs per class")
    df = build_demo_dataset(runs_per_class=runs_per_class)
    # Group by complete run_id, stratified explicitly by scenario and seeded run number.
    train_set = df[df["run_number"] < runs_per_class - 4]
    val_set = df[df["run_number"].isin([runs_per_class - 4, runs_per_class - 3])]
    test_set = df[df["run_number"] >= runs_per_class - 2]
    assert not (set(train_set.run_id) & set(test_set.run_id))
    assert not (set(train_set.run_id) & set(val_set.run_id))
    model = RandomForestClassifier(
        n_estimators=120, min_samples_leaf=2,
        class_weight="balanced", random_state=42, n_jobs=-1
    )
    cols = list(FEATURE_NAMES)
    model.fit(train_set[cols], train_set.label)
    def evaluate(split):
        target = split.label
        pred = model.predict(split[cols])
        return {
            "accuracy": float(accuracy_score(target, pred)),
            "classification_report": classification_report(target, pred, output_dict=True, zero_division=0),
            "confusion_matrix": confusion_matrix(target, pred, labels=sorted(df.label.unique())).tolist(),
            "runs": sorted(split.run_id.unique().tolist()),
        }

    validation = evaluate(val_set)
    test = evaluate(test_set)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    model_file = out / "motor_demo.joblib"
    joblib.dump(model, model_file)
    metadata = {
        "model_version": "synthetic-demo-rf-v1",
        "data_type": "SYNTHETIC_DEMO",
        "warning": "Synthetic evaluation is not physical fault-detection accuracy.",
        "features": cols,
        "classes": [str(x) for x in model.classes_],
        "runs_per_class": runs_per_class,
        "windows_per_run": 8,
        "random_state": 42,
        "sklearn_version": sklearn.__version__,
        "numpy_version": np.__version__,
        "validation": validation,
        "test": test,
    }
    model_file.with_suffix(".json").write_text(json.dumps(metadata, indent=2))
    print(f"Saved DEMONSTRATION model: {model_file}")
    print("Synthetic held-out run test accuracy:", round(test["accuracy"], 4))
    print("WARNING: This is NOT real-machine fault accuracy.")
    return metadata


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--output", default=str(ROOT / "ai" / "models"))
    p.add_argument("--runs-per-class", type=int, default=12)
    args = p.parse_args()
    train(args.output, args.runs_per_class)


if __name__ == "__main__":
    main()
